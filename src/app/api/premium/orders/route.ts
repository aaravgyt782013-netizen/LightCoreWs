import crypto from "node:crypto";
import { NextRequest, NextResponse } from "next/server";
import { SESSION_COOKIE, unsealSession } from "@/lib/session";
import {
  createPremiumInvoice,
  listPremiumInvoices,
  type BillingCycle,
  type PremiumTier,
} from "@/lib/premium-store";
import { ensureSessionUserRecorded } from "@/lib/auth-store";
import { appendLogs } from "@/lib/log-store";
import { sendDiscordLogEmbed } from "@/lib/discord-webhook";

export const dynamic = "force-dynamic";

export async function GET(req: NextRequest) {
  const session = unsealSession(req.cookies.get(SESSION_COOKIE)?.value);
  if (!session) {
    return NextResponse.json({ error: "Sign in required" }, { status: 401 });
  }
  const all = await listPremiumInvoices(200);
  const mine = all.filter((i) => i.userId === session.user.id).slice(0, 20);
  return NextResponse.json(
    { invoices: mine },
    { headers: { "Cache-Control": "no-store, max-age=0" } },
  );
}

/**
 * Creates a premium order summary. No payment is processed on the website.
 * The user downloads the order summary and contacts the Support Server
 * where the owner provides the payment QR and activates Premium within 24h.
 */
export async function POST(req: NextRequest) {
  const session = unsealSession(req.cookies.get(SESSION_COOKIE)?.value);
  if (!session) {
    return NextResponse.json(
      {
        error:
          "Please sign in with Discord first so the order summary can be associated with your account.",
      },
      { status: 401 },
    );
  }

  let body: {
    tier?: unknown;
    cycle?: unknown;
    guildId?: unknown;
    guildName?: unknown;
    buyerNote?: unknown;
  };
  try {
    body = (await req.json()) as typeof body;
  } catch {
    return NextResponse.json({ error: "Invalid JSON body" }, { status: 400 });
  }

  const tier = typeof body.tier === "string" ? (body.tier as PremiumTier) : "";
  const cycle =
    typeof body.cycle === "string" ? (body.cycle as BillingCycle) : "";
  if (
    !["plus", "pro", "ultra"].includes(tier) ||
    !["1m", "3m", "1y"].includes(cycle)
  ) {
    return NextResponse.json(
      { error: "Select a valid Premium plan and duration." },
      { status: 400 },
    );
  }

  const rawGuildId =
    typeof body.guildId === "string" ? body.guildId.trim() : "";
  const guildId = /^\d{15,22}$/.test(rawGuildId) ? rawGuildId : null;
  const guildName =
    guildId && typeof body.guildName === "string"
      ? body.guildName.trim().slice(0, 100) || null
      : null;
  const buyerNote =
    typeof body.buyerNote === "string"
      ? body.buyerNote.trim().slice(0, 240) || null
      : null;

  const avatarUrl = session.user.avatar
    ? `https://cdn.discordapp.com/avatars/${session.user.id}/${session.user.avatar}.png?size=128`
    : null;

  await ensureSessionUserRecorded(session);

  const created = await createPremiumInvoice({
    userId: session.user.id,
    username: session.user.username,
    globalName: session.user.globalName ?? null,
    avatarUrl,
    email: null,
    tier: tier as PremiumTier,
    cycle: cycle as BillingCycle,
    guildId,
    guildName,
    buyerNote,
  });

  if (!created.ok) {
    return NextResponse.json({ error: created.error }, { status: 400 });
  }

  const inv = created.invoice;

  await appendLogs([
    {
      id: crypto.randomUUID(),
      t: "PREMIUM",
      ok: true,
      msg: `invoice ${inv.invoiceId} generated by @${inv.username} · ${inv.tierName} (${inv.durationLabel}) · ${inv.currencySymbol}${inv.amount}`,
      guildId: inv.guildId ?? undefined,
      guild: inv.guildName ?? undefined,
      ts: inv.createdAt,
    },
  ]);

  await sendDiscordLogEmbed({
    title: `${inv.brandName} · New Premium Order Summary`,
    description: `\`@${inv.username}\` (\`${inv.userId}\`) created an order summary and was directed to contact the Support Server.`,
    color: 0xef4444,
    timestamp: inv.createdAt,
    fields: [
      { name: "Order Reference", value: `\`${inv.invoiceId}\``, inline: true },
      { name: "Verify Code", value: `\`${inv.verificationCode}\``, inline: true },
      {
        name: "Amount",
        value: `**${inv.currencySymbol}${inv.amount.toLocaleString("en-IN")} ${inv.currencyCode}**`,
        inline: true,
      },
      {
        name: "Plan & Duration",
        value: `${inv.tierName} · ${inv.durationLabel}`,
        inline: true,
      },
      {
        name: "Target Server",
        value: inv.guildId
          ? `${inv.guildName || "Server"} (\`${inv.guildId}\`)`
          : "Assign in ticket",
        inline: true,
      },
    ],
  });

  return NextResponse.json({ ok: true, invoice: inv }, { status: 201 });
}
